/*
 * Monochrome framebuffer drawing — see gfx.h.
 */

#include "gfx.h"

#include <math.h>
#include <stdlib.h>
#include <string.h>

static int org_x, org_y;

void gfx_set_origin(int dx, int dy)
{
    org_x = dx;
    org_y = dy;
}

void gfx_clear(uint8_t *fb)
{
    memset(fb, 0, GFX_FB_SIZE);
}

void gfx_pixel(uint8_t *fb, int x, int y, int color)
{
    x += org_x;
    y += org_y;
    if (x < 0 || x >= GFX_W || y < 0 || y >= GFX_H) return;
    uint8_t *b = &fb[(y >> 3) * GFX_W + x];
    uint8_t m = 1u << (y & 7);
    if (color == 1)      *b |= m;
    else if (color == 0) *b &= ~m;
    else                 *b ^= m;
}

void gfx_hline(uint8_t *fb, int x, int y, int w, int color)
{
    for (int i = 0; i < w; i++) gfx_pixel(fb, x + i, y, color);
}

void gfx_vline(uint8_t *fb, int x, int y, int h, int color)
{
    for (int i = 0; i < h; i++) gfx_pixel(fb, x, y + i, color);
}

void gfx_hline_dashed(uint8_t *fb, int x, int y, int w, int on, int off)
{
    for (int i = 0; i < w; i++) {
        if (i % (on + off) < on) gfx_pixel(fb, x + i, y, 1);
    }
}

void gfx_rect(uint8_t *fb, int x, int y, int w, int h, int color)
{
    if (w <= 0 || h <= 0) return;
    gfx_hline(fb, x, y, w, color);
    gfx_hline(fb, x, y + h - 1, w, color);
    gfx_vline(fb, x, y + 1, h - 2, color);
    gfx_vline(fb, x + w - 1, y + 1, h - 2, color);
}

void gfx_fill(uint8_t *fb, int x, int y, int w, int h, int color)
{
    for (int j = 0; j < h; j++) gfx_hline(fb, x, y + j, w, color);
}

void gfx_line(uint8_t *fb, int x0, int y0, int x1, int y1, int color)
{
    int dx = abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
    int dy = -abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;
    for (;;) {
        gfx_pixel(fb, x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

void gfx_fill_ellipse(uint8_t *fb, int cx, int cy, int rx, int ry, int color)
{
    if (rx <= 0 || ry <= 0) return;
    /* +0.5 on the vertical radius rounds off the single-pixel nubs at
       the top and bottom of small ellipses */
    float k = 1.0f / ((float)ry + 0.5f);
    for (int dy = -ry; dy <= ry; dy++) {
        float u = dy * k;
        int hw = (int)lroundf((float)rx * sqrtf(1.0f - u * u));
        gfx_hline(fb, cx - hw, cy + dy, 2 * hw + 1, color);
    }
}

void gfx_circle(uint8_t *fb, int cx, int cy, int r, int color)
{
    int x = r, y = 0, err = 1 - r;
    while (x >= y) {
        gfx_pixel(fb, cx + x, cy + y, color); gfx_pixel(fb, cx - x, cy + y, color);
        gfx_pixel(fb, cx + x, cy - y, color); gfx_pixel(fb, cx - x, cy - y, color);
        gfx_pixel(fb, cx + y, cy + x, color); gfx_pixel(fb, cx - y, cy + x, color);
        gfx_pixel(fb, cx + y, cy - x, color); gfx_pixel(fb, cx - y, cy - x, color);
        y++;
        if (err < 0) {
            err += 2 * y + 1;
        } else {
            x--;
            err += 2 * (y - x) + 1;
        }
    }
}

