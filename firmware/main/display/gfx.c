int gfx_tiny(uint8_t *fb, int x, int y, const char *s, int color)
{
    for (; *s; s++) {
        char c = *s;
        if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
        const char *p = strchr(tiny_chars, c);
        int idx = (p && c) ? (int)(p - tiny_chars) : 0;
        for (int row = 0; row < 5; row++) {
            for (int col = 0; col < 3; col++) {
                if (tiny_font[idx][row] & (4u >> col)) gfx_pixel(fb, x + col, y + row, color);
            }
        }
        x += 4;
    }
    return x;
}

int gfx_tiny_width(const char *s)
{
    int n = (int)strlen(s);
    return n ? 4 * n - 1 : 0;
}

