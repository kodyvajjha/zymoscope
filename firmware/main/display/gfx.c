void gfx_sprite(uint8_t *fb, int x, int y, const char *const *rows,
                int nrows, int scale, int color)
{
    for (int r = 0; r < nrows; r++) {
        for (int c = 0; rows[r][c]; c++) {
            if (rows[r][c] == '#') {
                gfx_fill(fb, x + c * scale, y + r * scale, scale, scale, color);
            }
        }
    }
}
