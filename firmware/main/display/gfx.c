/*  Seven-segment digits                                              */
/* ------------------------------------------------------------------ */

/* Segment bits: a b c d e f g */
static const uint8_t seg_digits[10] = {
    0x3F, 0x06, 0x5B, 0x4F, 0x66, 0x6D, 0x7D, 0x07, 0x7F, 0x6F,
};

static void seg_draw(uint8_t *fb, int x, int y, uint8_t segs, int w, int h, int t)
{
    int mid = y + (h - t) / 2;
    int vh1 = mid - y - t;            /* upper vertical length, between bars */
    int vh2 = (y + h - t) - (mid + t); /* lower vertical length */
    /* Horizontal bars are inset 1 px and verticals stop short of the bars,
       so the segments show the classic small gaps. */
    if (segs & 0x01) gfx_fill(fb, x + 1, y, w - 2, t, 1);                  /* a */
    if (segs & 0x02) gfx_fill(fb, x + w - t, y + t, t, vh1, 1);            /* b */
    if (segs & 0x04) gfx_fill(fb, x + w - t, mid + t, t, vh2, 1);          /* c */
    if (segs & 0x08) gfx_fill(fb, x + 1, y + h - t, w - 2, t, 1);          /* d */
    if (segs & 0x10) gfx_fill(fb, x, mid + t, t, vh2, 1);                  /* e */
    if (segs & 0x20) gfx_fill(fb, x, y + t, t, vh1, 1);                    /* f */
    if (segs & 0x40) gfx_fill(fb, x + 1, mid, w - 2, t, 1);                /* g */
}

static int big_advance(char c, int w, int t)
{
    return c == '.' ? t + 3 : w + 3;
}

int gfx_big(uint8_t *fb, int x, int y, const char *s, int w, int h, int t)
{
    for (; *s; s++) {
        char c = *s;
        if (c >= '0' && c <= '9') {
            seg_draw(fb, x, y, seg_digits[c - '0'], w, h, t);
        } else if (c == '-') {
            seg_draw(fb, x, y, 0x40, w, h, t);
        } else if (c == '.') {
            gfx_fill(fb, x + 1, y + h - t, t, t, 1);
        }
        x += big_advance(c, w, t);
    }
    return x;
}

int gfx_big_width(const char *s, int w, int t)
{
    int x = 0;
    for (; *s; s++) x += big_advance(*s, w, t);
    return x > 0 ? x - 3 : 0;
}

